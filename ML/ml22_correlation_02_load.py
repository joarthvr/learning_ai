# ! 상관행렬(Correlation Matrix) 해석
# ! 모든 컬럼을 두 개씩 짝지어 상관계수를 표로 만든 것 (df.corr())

# ============================================================
# ? iris 의 상관행렬 (pearson, 소수 둘째 자리)
# ============================================================
# ?           sep_len  sep_wid  pet_len  pet_wid  target
# ? sep_len      1.00    -0.12     0.87     0.82    0.78
# ? sep_wid     -0.12     1.00    -0.43    -0.37   -0.43
# ? pet_len      0.87    -0.43     1.00     0.96    0.95
# ? pet_wid      0.82    -0.37     0.96     1.00    0.96
# ? target       0.78    -0.43     0.95     0.96    1.00
# ? (sep = 꽃받침, pet = 꽃잎, len = 길이, wid = 너비)

# ============================================================
# ? 행과 열, 그리고 '행끼리' 상관
# ============================================================
# ? - 위 표의 행과 열은 둘 다 '컬럼(피처) 이름' 이다. 데이터의 행(샘플)이 아니다
# ? - 한 칸 = (행 이름의 컬럼) 과 (열 이름의 컬럼) 의 상관계수
# ? - df.corr()   : 열(피처)끼리 비교 → iris 는 5 x 5
# ? - df.T.corr() : 전치해서 행(샘플)끼리 비교 → iris 는 150 x 150
# ?                 "어떤 꽃과 어떤 꽃의 측정값 패턴이 비슷한가" 를 보는 것
# ? - 행끼리 볼 때 주의
# ?   · target 은 빼고 계산한다 (측정값이 아니라 정답이다)
# ?   · 컬럼마다 단위와 크기가 다르면 큰 컬럼이 패턴을 좌우한다 → 스케일링 먼저
# ?   · 값이 4개뿐이라 대부분 1 에 가깝게 나와 해석력이 약하다
# ? - 머신러닝에서 컬럼 정리에 쓰는 것은 열끼리(df.corr()) 다

# ============================================================
# ? 표 읽는 순서
# ============================================================
# ? 1) 대각선은 자기 자신과의 상관이라 항상 1 → 볼 필요 없다
# ? 2) 대각선 위아래는 대칭 → 한쪽 삼각형만 보면 된다
# ? 3) target 행(열) : 어떤 피처가 타깃과 같이 움직이는지
# ?    → pet_wid 0.96, pet_len 0.95 로 꽃잎이 품종 구분에 유력한 후보
# ? 4) 피처끼리 : 중복 정보 확인
# ?    → pet_len 과 pet_wid 가 0.96 으로 거의 같은 정보 (다중공선성)
# ?    → sep_len 도 꽃잎 두 피처와 0.8 이상
# ? 5) 음수 : sep_wid 는 다른 값들과 반대로 움직인다. -0.12 는 거의 관계가 없다

# ============================================================
# ? 해석할 때 주의
# ============================================================
# ? - target 은 품종 번호(0, 1, 2)다. 번호 순서가 우연히 꽃잎 크기 순서와 맞아서
# ?   크게 나온 것이고, 번호를 다르게 매기면 값이 달라진다. 참고용으로만 본다
# ? - 전체 상관과 품종 안에서의 상관은 다를 수 있다. 산점도를 품종별 색으로 확인한다
# ? - 상관이 높다고 바로 지우지 않는다. 지우기 전/후 점수를 같은 조건으로 비교한다
# ? - 컬럼을 고르는 데 쓸 거라면 train 데이터로만 계산한다 (위 표는 전체 150개 기준)

import joblib
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split

import pandas as pd

# (짝: ml22_correlation_01.py)
PATH_SAVE = './_save/joblib/'

#! 1. 데이터 세팅 ----------------------------------------------------
datasets = load_iris()
x, y = datasets.data, datasets.target
# save 파일과 똑같이 나눠야 같은 test 로 평가한다
x_train, x_test, y_train, y_test = train_test_split(
    x, y, train_size=0.8, random_state=1003, stratify=y
)

#! 2. 모델 불러오기 --------------------------------------------------
model = joblib.load(PATH_SAVE + 'ml22_iris.joblib')
print('불러오기 완료: ', type(model).__name__)

#! 4. 평가 -------------------------------------------------------------
print('acc: ', model.score(x_test, y_test))

#! 5. 상관관계 히트맵 ------------------------------------------------
# 상관행렬은 모델이 아니라 데이터(DataFrame)로 계산한다
df = pd.DataFrame(x, columns=datasets.feature_names)
df['target'] = y
print(df.corr())

sns.heatmap(
    data=df.corr(),
    square=True,
    annot=True,  # 칸에 숫자 표시
    cbar=True,  # 색상 막대
    vmin=-1,  # 색 범위를 상관계수 범위로 고정
    vmax=1,
    cmap='coolwarm',  # 음수는 파랑, 양수는 빨강
)
plt.tight_layout()  # 긴 컬럼 이름이 잘리지 않게
plt.show()
